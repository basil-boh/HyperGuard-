"""How circular is the dataset, really?

The original fixtures are unusable for evaluation because the victim scripts and the
classifier's indicator lists live in the same file — the test data was written from the
answer key. This module measures whether the replacement actually escaped that, instead of
assuming it did.

Two numbers:

* **Verbatim indicator rate** — the share of generated utterances containing an indicator
  string exactly. Some overlap is legitimate and unavoidable: real victims of a police
  impersonation scam do say "safe account". Near 100% would mean we regenerated the answer
  key; near 0% on the clean slice would mean the utterances are unrealistic.
* **Fixture overlap** — similarity to the shipped `victim_script` fixtures. This should be
  low. If it is high, the generator reproduced the fixtures and Option B is measuring
  nothing again.
"""

from __future__ import annotations

import re

from app.schemas import ScamArchetype
from app.services import scam_taxonomy as tax
from eval.metrics import pct
from eval.schema import Dataset, Slice


def _indicators() -> dict[ScamArchetype, list[str]]:
    return {a.key: list(a.indicators) for a in tax._LIBRARY}


def _fixtures() -> dict[ScamArchetype, list[str]]:
    return {a.key: list(a.victim_script) for a in tax._LIBRARY}


def _tokens(text: str) -> set[str]:
    return set(re.findall(r"[a-z']+", text.lower()))


def _jaccard(a: str, b: str) -> float:
    ta, tb = _tokens(a), _tokens(b)
    if not ta or not tb:
        return 0.0
    return len(ta & tb) / len(ta | tb)


def run(ds: Dataset) -> dict:
    indicators = _indicators()
    fixtures = _fixtures()

    by_slice: dict[str, dict] = {}
    for slice_ in (Slice.scam_clean, Slice.scam_adversarial):
        cases = ds.by_slice(slice_)
        hit_cases = 0
        hit_utterances = 0
        total_utterances = 0
        max_fixture_sim = []
        for c in cases:
            inds = [i.lower() for i in indicators.get(c.archetype, [])]
            case_hit = False
            for u in c.utterances:
                total_utterances += 1
                if any(i in u.lower() for i in inds):
                    hit_utterances += 1
                    case_hit = True
            hit_cases += int(case_hit)
            fx = fixtures.get(c.archetype, [])
            max_fixture_sim.append(
                max((_jaccard(c.speech, f) for f in fx), default=0.0)
            )
        by_slice[slice_.value] = {
            "n": len(cases),
            "cases_with_verbatim_indicator": hit_cases / len(cases) if cases else float("nan"),
            "utterances_with_verbatim_indicator": (
                hit_utterances / total_utterances if total_utterances else float("nan")
            ),
            "mean_fixture_similarity": (
                sum(max_fixture_sim) / len(max_fixture_sim) if max_fixture_sim else float("nan")
            ),
            "max_fixture_similarity": max(max_fixture_sim, default=float("nan")),
        }

    # For contrast: the shipped fixtures scored against themselves. This is what a fully
    # circular dataset looks like, and it's the number Option B used to be measuring.
    fixture_self = {
        "cases_with_verbatim_indicator": 1.0,
        "note": "the shipped victim_script fixtures, by construction",
    }
    return {"by_slice": by_slice, "reference": fixture_self, "generator": ds.generator}


def render(res: dict) -> str:
    L = ["## Dataset integrity — how circular is this?\n"]
    L.append(
        "The old fixtures were written in the same file as the indicator lists they're matched "
        "against, so testing on them proved nothing. These numbers check the replacement "
        "actually escaped that, rather than assuming it.\n"
    )
    L.append(f"Utterances generated by: **{res['generator']}**\n")
    L.append("| Slice | n | Cases containing a verbatim indicator | Utterances | Similarity to shipped fixtures |")
    L.append("|---|---|---|---|---|")
    for name, r in res["by_slice"].items():
        L.append(
            f"| `{name}` | {r['n']} | {pct(r['cases_with_verbatim_indicator'])} | "
            f"{pct(r['utterances_with_verbatim_indicator'])} | "
            f"{r['mean_fixture_similarity']:.2f} mean / {r['max_fixture_similarity']:.2f} max |"
        )
    L.append(
        "\n**How to read this.** Some verbatim overlap on the clean slice is *correct* — real "
        "victims of a police-impersonation scam genuinely say \"safe account\", and utterances "
        "with none of the natural vocabulary would be unrealistic. What matters is that the "
        "adversarial slice is much lower (that's the test working) and that fixture similarity "
        "stays low (the generator didn't rediscover the answer key). The old fixtures would "
        "score 100% on column three by construction."
    )
    return "\n".join(L)
