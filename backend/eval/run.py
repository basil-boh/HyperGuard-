"""Run the evaluation and write eval/results/REPORT.md.

    python -m eval.run --all
    python -m eval.run --option b --option d
    python -m eval.run --all --no-llm      # deterministic options only
"""

from __future__ import annotations

import argparse
import asyncio
import json
from datetime import datetime, timezone
from pathlib import Path

from app.config import get_settings
from app.services.llm import LLMClient
from eval import contamination, option_a, option_b, option_c, option_d
from eval.generate import DATA_PATH, load

RESULTS = Path(__file__).parent / "results"

_PREAMBLE = """# HyperGuard — Evaluation Results

Generated by `python -m eval.run`. Every figure below is a measurement against a baseline,
not a claim in isolation. Design rationale is in [EVALUATION.md](../../EVALUATION.md);
the audit that motivated it is in [FUNCTIONALITY.md](../../FUNCTIONALITY.md).

## Read this first — what these numbers are not

The dataset is **synthetic**. Transfer features are drawn from distributions written by
hand in `eval/generate.py`; utterances are LLM-generated from plain-language scam briefs.
That design choice buys one thing and costs another:

* It **buys** an escape from the circularity that made the old fixtures useless — the
  utterances are produced without ever seeing the classifier's indicator lists, and the
  dataset-integrity section below measures how well that worked.
* It **costs** external validity. These results describe how the system behaves on the
  world as `generate.py` imagines it. If those distributions are wrong about how scams
  differ from legitimate transfers, every number here is wrong in the same direction, and
  confidently so.

**What would fix that:** sourced cases from SPF scam briefs, ScamShield advisories, and
published enforcement write-ups, labelled by two annotators with inter-rater agreement
reported. That is the upgrade that turns these from internal-consistency checks into
evidence. Until then, do not put these numbers on a slide without the word "synthetic"
next to them.

"""


async def main() -> None:
    ap = argparse.ArgumentParser(description="Run the HyperGuard evaluation suite.")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--option", action="append", default=[], choices=list("abcd"))
    ap.add_argument("--no-llm", action="store_true", help="skip LLM-dependent comparisons")
    ap.add_argument("--dataset", type=Path, default=DATA_PATH)
    ap.add_argument("--out", type=Path, default=RESULTS / "REPORT.md")
    args = ap.parse_args()

    wanted = set("abcd") if args.all or not args.option else set(args.option)
    ds = load(args.dataset)

    settings = get_settings()
    llm = LLMClient(settings)
    if args.no_llm:
        class _Off(LLMClient):
            @property
            def enabled(self) -> bool:
                return False
        llm = _Off(settings)

    print(f"dataset: {len(ds.cases)} cases  ({', '.join(f'{k}={v}' for k, v in sorted(ds.counts().items()))})")
    print(f"llm:     {'on' if llm.enabled else 'off'}")

    sections: list[str] = [_PREAMBLE]
    sections.append(
        f"**Dataset:** {len(ds.cases)} cases — "
        + ", ".join(f"`{k}` {v}" for k, v in sorted(ds.counts().items()))
        + f". Utterances: {ds.generator}. LLM comparisons: "
        + ("enabled" if llm.enabled else "**disabled**")
        + ".\n\n---\n"
    )

    raw: dict = {}

    print("· dataset integrity")
    raw["contamination"] = contamination.run(ds)
    sections.append(contamination.render(raw["contamination"]) + "\n\n---\n")

    if "a" in wanted:
        print("· option A — risk engine vs baselines")
        raw["a"] = await option_a.run(ds, llm)
        sections.append(option_a.render(raw["a"]) + "\n\n---\n")
    if "b" in wanted:
        print("· option B — classifier, clean vs reworded")
        raw["b"] = await option_b.run(ds, llm)
        sections.append(option_b.render(raw["b"]) + "\n\n---\n")
    if "c" in wanted:
        print("· option C — does the conversation change anything")
        raw["c"] = await option_c.run(ds, llm)
        sections.append(option_c.render(raw["c"]) + "\n\n---\n")
    if "d" in wanted:
        print("· option D — explainability")
        raw["d"] = option_d.run(ds)
        sections.append(option_d.render(raw["d"]) + "\n\n---\n")

    sections.append(
        f"\n_Run at {datetime.now(timezone.utc).isoformat(timespec='seconds')} · "
        f"`python -m eval.run --all`_\n"
    )

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(sections), encoding="utf-8")
    (args.out.parent / "results.json").write_text(
        json.dumps(raw, indent=1, default=str), encoding="utf-8"
    )
    print(f"\nwrote {args.out}")


if __name__ == "__main__":
    asyncio.run(main())
